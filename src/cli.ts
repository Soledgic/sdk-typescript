#!/usr/bin/env node

import { createServer } from 'http'
import { execFile } from 'child_process'
import { writeFileSync, readFileSync, existsSync } from 'fs'
import { join } from 'path'
import { fileURLToPath } from 'url'

// SOLEDGIC_AUTH_URL overrides the website used for the browser auth flow during `init`.
// SOLEDGIC_BASE_URL is reserved for the API base URL used by doctor and the SDK at runtime —
// they intentionally point to different hosts (app vs api.) so they must be separate vars.
const AUTH_URL = process.env.SOLEDGIC_AUTH_URL ?? 'https://soledgic.com'
const TIMEOUT_MS = 300_000

function pickPort(): number {
  return Math.floor(Math.random() * 10_000) + 50_000
}

function openBrowser(url: string): void {
  if (process.platform === 'darwin') {
    execFile('open', [url], () => undefined)
  } else if (process.platform === 'win32') {
    execFile('cmd', ['/c', 'start', '', url], { windowsHide: true }, () => undefined)
  } else {
    execFile('xdg-open', [url], () => undefined)
  }
}

function writeEnv(key: string): void {
  const envPath = join(process.cwd(), '.env')
  const line = `SOLEDGIC_API_KEY=${key}`

  if (existsSync(envPath)) {
    const content = readFileSync(envPath, 'utf8')
    // Replace either the new (API_KEY) or legacy (SECRET_KEY) entry if present.
    if (/^SOLEDGIC_API_KEY=/m.test(content)) {
      writeFileSync(envPath, content.replace(/^SOLEDGIC_API_KEY=.*/m, line))
      return
    }
    if (/^SOLEDGIC_SECRET_KEY=/m.test(content)) {
      writeFileSync(envPath, content.replace(/^SOLEDGIC_SECRET_KEY=.*/m, line))
      return
    }
    writeFileSync(envPath, content.endsWith('\n') ? content + line + '\n' : content + '\n' + line + '\n')
  } else {
    writeFileSync(envPath, line + '\n')
  }
}

